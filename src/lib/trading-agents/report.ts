import { REPORT_SECTIONS, type RunRecord } from "./types";

function fmt(n?: number) {
  return n === undefined ? "—" : n.toLocaleString(undefined, { maximumFractionDigits: 2 });
}

export function buildMarkdownReport(run: RunRecord): string {
  const d = run.decision;
  const c = run.config;
  const lines: string[] = [];

  lines.push(`# TradingAgents Decision Memo — ${c.ticker}`);
  lines.push("");
  lines.push(`**Analysis date:** ${c.analysisDate}  `);
  lines.push(`**Provider / models:** ${c.provider} — quick: ${c.quickModel}, deep: ${c.deepModel}  `);
  lines.push(`**Research depth:** ${c.researchDepth}  `);
  lines.push(`**Analysts engaged:** ${c.analysts.join(", ") || "—"}  `);
  lines.push(`**Run id:** ${run.id} (${run.source === "sample" ? "sample data" : "live engine"})`);
  lines.push("");

  if (d) {
    lines.push("## Executive summary");
    lines.push("");
    lines.push(`**Recommendation: ${d.action}** · Confidence ${d.confidence}% · Consensus ${d.consensus}`);
    lines.push("");
    lines.push(d.executiveSummary);
    lines.push("");
    lines.push("| Field | Value |");
    lines.push("| --- | --- |");
    lines.push(`| Entry price | ${fmt(d.entryPrice)} |`);
    lines.push(`| Stop loss | ${fmt(d.stopLoss)} |`);
    lines.push(`| Position sizing | ${d.positionSizing ?? "—"} |`);
    lines.push("");
    lines.push("## Key bullish signals");
    lines.push("");
    d.bullPoints.forEach((p) => lines.push(`- ${p}`));
    lines.push("");
    lines.push("## Key bearish risks");
    lines.push("");
    d.bearPoints.forEach((p) => lines.push(`- ${p}`));
    lines.push("");
  }

  lines.push("## Agent stances");
  lines.push("");
  lines.push("| Agent | Stance | Score |");
  lines.push("| --- | --- | --- |");
  run.stances.forEach((s) => lines.push(`| ${s.agent} | ${s.stance} | ${s.score} |`));
  lines.push("");

  lines.push("## Agent contributions");
  lines.push("");
  REPORT_SECTIONS.forEach((s) => {
    const body = run.reports[s.key];
    if (!body) return;
    lines.push(`### ${s.label} (${s.team})`);
    lines.push("");
    lines.push(body.trim());
    lines.push("");
  });

  lines.push("## Run audit trail");
  lines.push("");
  lines.push("| Metric | Value |");
  lines.push("| --- | --- |");
  lines.push(`| Started | ${run.startedAt} |`);
  lines.push(`| Runtime | ${run.stats.runtimeSeconds}s |`);
  lines.push(`| LLM calls | ${run.stats.llmCalls} |`);
  lines.push(`| Tool calls | ${run.stats.toolCalls} |`);
  lines.push(`| Tokens in / out | ${run.stats.tokensIn} / ${run.stats.tokensOut} |`);
  lines.push(`| Reports | ${run.stats.reportsDone}/${run.stats.reportsTotal} |`);
  lines.push("");
  lines.push(
    "_Decision-support prototype. Generated by TradingAgents Workbench on top of the TradingAgents multi-agent framework (Tauric Research, 2024). Not investment advice and not an autonomous trading system._",
  );

  return lines.join("\n");
}

function escapeHtml(s: string) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** Promote bold field labels from model output into real subheadings. */
function normalizeReportMarkdown(md: string): string {
  const labelledField = /\*\*([^*\n]{2,70}?)(?:(?::\*\*|\*\*[:：])[ \t]*|\*\*(?=\s*$))/g;

  return md
    .split("\n")
    .flatMap((raw) => {
      const trimmed = raw.trimStart();
      if (trimmed.startsWith("|") || trimmed.startsWith("- ")) return [raw];

      const matches = [...raw.matchAll(labelledField)];
      if (matches.length === 0) return [raw];

      const parts: string[] = [];
      const firstIndex = matches[0]?.index ?? 0;
      const before = raw.slice(0, firstIndex).trim();
      if (before) parts.push(before, "");

      matches.forEach((match, index) => {
        const label = match[1]?.trim();
        if (!label) return;
        const start = (match.index ?? 0) + match[0].length;
        const end = matches[index + 1]?.index ?? raw.length;
        const body = raw.slice(start, end).trim();
        parts.push(`### ${label}`);
        if (body) parts.push("", body);
        if (index < matches.length - 1) parts.push("");
      });

      return parts;
    })
    .join("\n");
}

/** Collapse repeated heading/value pairs from JSON-derived reports into tables. */
function compactFieldGroups(md: string): string {
  const lines = md.split("\n");
  const output: string[] = [];
  let index = 0;

  while (index < lines.length) {
    const fields: Array<[string, string]> = [];
    let cursor = index;

    while (cursor < lines.length) {
      const heading = /^#{2,4}\s+(.+)$/.exec(lines[cursor]?.trim() ?? "");
      if (!heading) break;
      let valueIndex = cursor + 1;
      while (valueIndex < lines.length && !(lines[valueIndex]?.trim())) valueIndex += 1;
      const value = lines[valueIndex]?.trim() ?? "";
      if (!value || /^#{1,4}\s+|^[-|]/.test(value)) break;
      fields.push([heading[1] ?? "Field", value]);
      cursor = valueIndex + 1;
      while (cursor < lines.length && !(lines[cursor]?.trim())) cursor += 1;
    }

    if (fields.length >= 2) {
      output.push("| Field | Value |", "| --- | --- |");
      fields.forEach(([label, value]) => output.push(`| ${label.replace(/\|/g, "\\|")} | ${value.replace(/\|/g, "\\|")} |`));
      output.push("");
      index = cursor;
      continue;
    }

    output.push(lines[index] ?? "");
    index += 1;
  }

  return output.join("\n");
}

/** Minimal markdown -> HTML for the exported standalone report. */
export function markdownToHtml(md: string, compactFields = true): string {
  const out: string[] = [];
  let inList = false;
  let inTable = false;

  const closeList = () => {
    if (inList) {
      out.push("</ul>");
      inList = false;
    }
  };
  const closeTable = () => {
    if (inTable) {
      out.push("</tbody></table>");
      inTable = false;
    }
  };

  const inline = (t: string) =>
    escapeHtml(t)
      .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
      .replace(/_(.+?)_/g, "<em>$1</em>");

  const cleaned = md.replace(/[ \t]+\\[ \t]*$/gm, "");
  const normalized = normalizeReportMarkdown(cleaned);
  for (const raw of (compactFields ? compactFieldGroups(normalized) : normalized).split("\n")) {
    const line = raw.trimEnd();
    if (!line.trim()) {
      closeList();
      closeTable();
      continue;
    }
    const heading = /^(#{1,4})\s+(.*)$/.exec(line);
    if (heading) {
      closeList();
      closeTable();
      const level = heading[1]?.length ?? 1;
      out.push(`<h${level}>${inline(heading[2] ?? "")}</h${level}>`);
      continue;
    }
    if (/^---+$/.test(line.trim())) {
      closeList();
      closeTable();
      out.push("<hr />");
      continue;
    }
    if (line.startsWith("|")) {
      const cells = line.split("|").slice(1, -1).map((c) => c.trim());
      if (cells.every((c) => /^-{2,}$/.test(c))) continue;
      closeList();
      if (!inTable) {
        out.push("<table><thead><tr>" + cells.map((c) => `<th>${inline(c)}</th>`).join("") + "</tr></thead><tbody>");
        inTable = true;
        continue;
      }
      out.push("<tr>" + cells.map((c) => `<td>${inline(c)}</td>`).join("") + "</tr>");
      continue;
    }
    closeTable();
    if (line.startsWith("- ")) {
      if (!inList) {
        out.push("<ul>");
        inList = true;
      }
      out.push(`<li>${inline(line.slice(2))}</li>`);
      continue;
    }
    closeList();
    out.push(`<p>${inline(line.replace(/\s{2}$/, ""))}</p>`);
  }
  closeList();
  closeTable();
  return out.join("\n");
}

