import { useMemo, useState } from "react";
import { Check, Copy, Download } from "lucide-react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import {
  DEFAULT_ALPHA_VANTAGE_KEY,
  DEFAULT_FRED_KEY,
  DEFAULT_FRONTEND_ORIGINS,
  DEFAULT_PUBLIC_BASE_URL,
  PROVIDERS,
  providerById,
} from "@/lib/trading-agents/providers";

/**
 * Builds the engine's .env file (and the matching initialSetup.py answers)
 * from a few inputs, so the user never has to remember model ids or key names.
 * Everything stays in the browser — nothing is sent anywhere.
 */
export function EnvBuilder() {
  const [providerId, setProviderId] = useState("deepseek");
  const provider = providerById(providerId);
  const [keys, setKeys] = useState<Record<string, string>>({});
  const [deepModel, setDeepModel] = useState<string | null>(null);
  const [quickModel, setQuickModel] = useState<string | null>(null);
  const [fred, setFred] = useState(DEFAULT_FRED_KEY);
  const [alpha, setAlpha] = useState(DEFAULT_ALPHA_VANTAGE_KEY);
  const [baseUrl, setBaseUrl] = useState(DEFAULT_PUBLIC_BASE_URL);
  const [origins, setOrigins] = useState(DEFAULT_FRONTEND_ORIGINS);

  const deep = deepModel ?? provider.defaults[0];
  const quick = quickModel ?? provider.defaults[1];

  const envText = useMemo(() => {
    const lines: string[] = [
      "# TradingAgents engine settings — generated by the dashboard setup page",
      "",
      "# --- Where the engine runs and who may call it ---",
      `PUBLIC_BASE_URL=${baseUrl}`,
      `FRONTEND_ORIGINS=${origins}`,
      "",
      "# --- AI provider ---",
      `LLM_PROVIDER=${provider.id}`,
      `DEEP_THINK_LLM=${deep}`,
      `QUICK_THINK_LLM=${quick}`,
    ];
    for (const k of provider.envKeys) lines.push(`${k}="${keys[k] ?? ""}"`);
    lines.push(
      "",
      "# --- Market and economic data ---",
      `ALPHA_VANTAGE_API_KEY="${alpha}"`,
      `FRED_API_KEY="${fred}"`,
      "",
      "# --- Performance ---",
      "TRADINGAGENTS_PARALLEL_ANALYSTS=1",
      "TRADINGAGENTS_DATA_CACHE=1",
      "TRADINGAGENTS_DATA_CACHE_TTL=21600",
      "RUN_WORKER_COUNT=2",
    );
    return lines.join("\n");
  }, [provider, keys, deep, quick, alpha, fred, baseUrl, origins]);

  const setKey = (name: string, value: string) =>
    setKeys((prev) => ({ ...prev, [name]: value }));

  const download = () => {
    const blob = new Blob([envText + "\n"], { type: "text/plain" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = "env";
    a.click();
    URL.revokeObjectURL(a.href);
  };

  return (
    <div className="panel mt-4 space-y-5 p-4 sm:p-5">
      <div className="grid gap-4 sm:grid-cols-2">
        <div className="space-y-1.5">
          <Label className="label-caps">AI provider</Label>
          <Select
            value={providerId}
            onValueChange={(v) => {
              setProviderId(v);
              setDeepModel(null);
              setQuickModel(null);
            }}
          >
            <SelectTrigger>
              <SelectValue />
            </SelectTrigger>
            <SelectContent>
              {PROVIDERS.map((p) => (
                <SelectItem key={p.id} value={p.id}>
                  {p.label}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
          {provider.keyUrl && (
            <a
              className="inline-block text-xs font-medium underline underline-offset-2 hover:text-primary"
              href={provider.keyUrl}
              target="_blank"
              rel="noreferrer"
            >
              Get a key for {provider.label}
            </a>
          )}
        </div>

        <div className="grid gap-4 sm:grid-cols-2">
          <div className="space-y-1.5">
            <Label className="label-caps">Deep model</Label>
            {provider.deep.length ? (
              <Select value={deep} onValueChange={setDeepModel}>
                <SelectTrigger>
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  {provider.deep.map((m) => (
                    <SelectItem key={m} value={m}>
                      {m}
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
            ) : (
              <Input value={deep} onChange={(e) => setDeepModel(e.target.value)} className="font-mono" />
            )}
          </div>
          <div className="space-y-1.5">
            <Label className="label-caps">Quick model</Label>
            {provider.quick.length ? (
              <Select value={quick} onValueChange={setQuickModel}>
                <SelectTrigger>
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  {provider.quick.map((m) => (
                    <SelectItem key={m} value={m}>
                      {m}
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
            ) : (
              <Input value={quick} onChange={(e) => setQuickModel(e.target.value)} className="font-mono" />
            )}
          </div>
        </div>
      </div>

      {provider.note && <p className="text-sm text-muted-foreground">{provider.note}</p>}

      {provider.envKeys.length > 0 && (
        <div className="grid gap-4 sm:grid-cols-2">
          {provider.envKeys.map((name) => (
            <div key={name} className="space-y-1.5">
              <Label htmlFor={name} className="label-caps">
                {name}
              </Label>
              <Input
                id={name}
                type={name.endsWith("KEY") ? "password" : "text"}
                autoComplete="off"
                value={keys[name] ?? ""}
                onChange={(e) => setKey(name, e.target.value)}
                placeholder={name.endsWith("ENDPOINT") ? "https://…" : "paste your key"}
                className="font-mono"
              />
            </div>
          ))}
        </div>
      )}

      <div className="grid gap-4 sm:grid-cols-2">
        <div className="space-y-1.5">
          <Label htmlFor="alpha" className="label-caps">
            Alpha Vantage key
          </Label>
          <Input id="alpha" value={alpha} onChange={(e) => setAlpha(e.target.value)} className="font-mono" />
          <p className="text-xs text-muted-foreground">
            A shared starter key is filled in. It is rate limited — get your own free key at{" "}
            <a
              className="underline underline-offset-2 hover:text-primary"
              href="https://www.alphavantage.co/support/#api-key"
              target="_blank"
              rel="noreferrer"
            >
              alphavantage.co
            </a>
            .
          </p>
        </div>
        <div className="space-y-1.5">
          <Label htmlFor="fred" className="label-caps">
            FRED key
          </Label>
          <Input id="fred" value={fred} onChange={(e) => setFred(e.target.value)} className="font-mono" />
          <p className="text-xs text-muted-foreground">
            A shared starter key is filled in. Your own free key:{" "}
            <a
              className="underline underline-offset-2 hover:text-primary"
              href="https://fredaccount.stlouisfed.org/apikeys"
              target="_blank"
              rel="noreferrer"
            >
              fredaccount.stlouisfed.org
            </a>
            .
          </p>
        </div>
      </div>

      <div className="grid gap-4 sm:grid-cols-2">
        <div className="space-y-1.5">
          <Label htmlFor="pub" className="label-caps">
            Engine address (PUBLIC_BASE_URL)
          </Label>
          <Input id="pub" value={baseUrl} onChange={(e) => setBaseUrl(e.target.value)} className="font-mono" />
        </div>
        <div className="space-y-1.5">
          <Label htmlFor="orig" className="label-caps">
            Allowed dashboards (FRONTEND_ORIGINS)
          </Label>
          <Input id="orig" value={origins} onChange={(e) => setOrigins(e.target.value)} className="font-mono" />
        </div>
      </div>

      <div>
        <div className="flex flex-wrap items-center gap-2">
          <p className="mr-auto text-sm font-medium">Your .env file</p>
          <Button
            type="button"
            variant="outline"
            size="sm"
            className="gap-1.5"
            onClick={() => {
              void navigator.clipboard.writeText(envText);
              toast.success("Copied — paste it into .env");
            }}
          >
            <Copy className="size-3.5" /> Copy
          </Button>
          <Button type="button" variant="outline" size="sm" className="gap-1.5" onClick={download}>
            <Download className="size-3.5" /> Download
          </Button>
        </div>
        <pre className="mt-2 overflow-x-auto rounded-md border border-rule bg-muted/60 p-3 font-mono text-xs leading-relaxed">
          {envText}
        </pre>
        <p className="mt-2 flex items-start gap-2 text-xs text-muted-foreground">
          <Check className="mt-0.5 size-3.5 shrink-0 text-bull" />
          Nothing here leaves your browser. Save the file as{" "}
          <code className="rounded bg-muted px-1 font-mono">.env</code> in the engine folder, then run{" "}
          <code className="rounded bg-muted px-1 font-mono">python initialSetup.py</code> and press Enter at
          each prompt to accept these values.
        </p>
      </div>
    </div>
  );
}
